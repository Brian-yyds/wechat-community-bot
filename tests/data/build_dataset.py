def dump_jsonl(path: Path, rows):
    with path.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def main():
    messages = build_messages()
    negatives = build_negative()
    ids = [r["id"] for r in messages]
    assert len(ids) == len(set(ids)), "messages id 重复"
    assert len(messages) >= 120, f"messages 不足 120：{len(messages)}"
    cats = {}
    for r in messages:
        cats[r["expected_category"]] = cats.get(r["expected_category"], 0) + 1
    required = ["提问", "行情讨论", "广告刷屏", "公告回复", "闲聊/无关", "需人工"]
    missing = [c for c in required if cats.get(c, 0) == 0]
    if missing:
        raise SystemExit(f"缺少类别: {missing}")
    dump_jsonl(OUT_DIR / "messages.jsonl", messages)
    dump_jsonl(OUT_DIR / "negative_forbidden.jsonl", negatives)
    print(f"messages.jsonl: {len(messages)} 条，分类分布: {cats}")
    print(f"negative_forbidden.jsonl: {len(negatives)} 条")
    return 0


if __name__ == "__main__":
    sys.exit(main())
